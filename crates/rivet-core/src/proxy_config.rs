use crate::config::RivetConfig;
use crate::paths::RivetPaths;

/// Render a minimal CLIProxyAPI v8 config for Rivet's managed sidecar.
///
/// Binds localhost only, leaves client `access.api-keys` empty so Claude Code can
/// keep its claude.ai login (connectors stay enabled when only
/// `ANTHROPIC_BASE_URL` is set), enables request logging (required for the Rivet
/// ingest sink), and stores OAuth material under Application Support — never in
/// the user's default `~/.cli-proxy-api`.
pub fn render_proxy_config(config: &RivetConfig, paths: &RivetPaths) -> String {
    let auth_dir = paths.proxy_auth_dir();
    format!(
        r#"# Generated by Rivet — do not put provider credentials here.
# OAuth tokens live under oauth.auth-dir. Client api-keys stay empty so Claude
# Code can use claude.ai auth against ANTHROPIC_BASE_URL without disabling connectors.
config-version: 8

server:
  host: "127.0.0.1"
  port: {port}
  commercial-mode: false
  discovery:
    enabled: false

management:
  allow-remote: false
  # Enables /v0|/v8 management credential + quota APIs for Rivet (not the HTML panel).
  secret-key: "{mgmt_key}"
  disable-control-panel: true

access:
  api-keys: []

oauth:
  auth-dir: "{auth_dir}"

observability:
  logs:
    debug: false
    logging-to-file: true
    request-log: true
    # Cap on-disk request logs (full prompts); cleaner is off when unset/0.
    logs-max-total-size-mb: 256
  usage:
    usage-statistics-enabled: true
"#,
        port = config.proxy_port,
        mgmt_key = if config.management_secret.trim().is_empty() {
            &config.proxy_access_key
        } else {
            &config.management_secret
        },
        auth_dir = auth_dir.as_str(),
    )
}

/// Write (or overwrite) the managed proxy config.yaml.
pub fn write_proxy_config(config: &RivetConfig, paths: &RivetPaths) -> anyhow::Result<()> {
    paths.ensure()?;
    let yaml = render_proxy_config(config, paths);
    std::fs::write(paths.proxy_config_file().as_std_path(), yaml)?;
    Ok(())
}

/// Claude Code `settings.json` fragment pointing at Rivet's proxy.
///
/// Only sets `ANTHROPIC_BASE_URL`. Leaving `ANTHROPIC_AUTH_TOKEN` /
/// `ANTHROPIC_API_KEY` unset keeps Claude Code on claude.ai login so connectors
/// stay enabled; Rivet's localhost proxy accepts unauthenticated clients and
/// uses linked provider OAuth for upstream.
pub fn claude_settings_json(config: &RivetConfig) -> String {
    format!(
        "{{\n  \"env\": {{\n    \"ANTHROPIC_BASE_URL\": \"{}\"\n  }}\n}}\n",
        config.proxy_base_url(),
    )
}

/// Codex `config.toml` fragment pointing at Rivet's proxy.
pub fn codex_config_toml(config: &RivetConfig) -> String {
    format!(
        r#"model_provider = "rivet"

[model_providers.rivet]
name = "Rivet"
base_url = "{}/v1"
wire_api = "responses"
requires_openai_auth = false
supports_websockets = true
experimental_bearer_token = "{}"
"#,
        config.proxy_base_url(),
        config.proxy_access_key
    )
}

/// Claude Code MCP server entry for Rivet's local history tools (streamable HTTP).
pub fn claude_mcp_json(config: &RivetConfig) -> String {
    format!(
        r#"{{
  "mcpServers": {{
    "rivet": {{
      "type": "http",
      "url": "{}"
    }}
  }}
}}
"#,
        config.mcp_url()
    )
}
